package dev.workbench;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;

/** 验证旧事件表升级时保留历史记录，并允许重复执行初始化脚本。 */
class CheckpointEventMigrationTest {
  @Test
  void addsReasonCodeWithoutRewritingLegacyEvents() {
    var dataSource =
        new DriverManagerDataSource(
            "jdbc:h2:mem:checkpoint_migration_"
                + java.util.UUID.randomUUID()
                + ";DB_CLOSE_DELAY=-1",
            "sa",
            "");
    var jdbc = new JdbcTemplate(dataSource);
    jdbc.execute(
        "CREATE TABLE events (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "run_id VARCHAR(36) NOT NULL, event_type VARCHAR(50) NOT NULL, "
            + "message VARCHAR(2000) NOT NULL, created_at VARCHAR(40) NOT NULL)");
    jdbc.update(
        "INSERT INTO events(run_id,event_type,message,created_at) VALUES(?,?,?,?)",
        "legacy-run",
        "CHECKPOINT_SKIPPED",
        "旧说明",
        "2026-01-01T00:00:00Z");
    var migration = new ResourceDatabasePopulator(new ClassPathResource("schema.sql"));
    migration.execute(dataSource);
    migration.execute(dataSource);
    var event =
        jdbc.queryForMap("SELECT message, reason_code FROM events WHERE run_id=?", "legacy-run");
    assertEquals("旧说明", event.get("MESSAGE"));
    assertNull(event.get("REASON_CODE"));
  }
}
